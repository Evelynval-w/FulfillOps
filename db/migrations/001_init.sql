-- 001_init.sql: core schema for FulfillOps.
-- The migration runner applies each file in its own transaction and records it in
-- schema_migrations (created by the runner itself, before the first migration).
-- All timestamps are timestamptz set by the database clock (one clock for leases and retries).

-- Catalog and stock. The CHECK constraints are the last line of defense for invariant I1.
CREATE TABLE products (
    sku              text    PRIMARY KEY,
    unit_price_cents integer NOT NULL CHECK (unit_price_cents > 0),
    available        integer NOT NULL CHECK (available >= 0)
);

-- One row per accepted order. UNIQUE (idempotency_key) enforces invariant I2 across replicas.
-- id is text (generated by the app as a uuid4) so a malformed ID in GET gives a clean 404.
CREATE TABLE orders (
    id              text        PRIMARY KEY,
    customer_id     text        NOT NULL CHECK (char_length(customer_id) BETWEEN 1 AND 64),
    idempotency_key text        NOT NULL UNIQUE CHECK (char_length(idempotency_key) BETWEEN 8 AND 128),
    payload_hash    text        NOT NULL,
    status          text        NOT NULL DEFAULT 'queued'
                    CHECK (status IN ('queued', 'processing', 'completed', 'failed')),
    total_cents     integer     NOT NULL CHECK (total_cents > 0),
    created_at      timestamptz NOT NULL DEFAULT now(),
    updated_at      timestamptz NOT NULL DEFAULT now()
);

-- Order lines, already added together per SKU (the PK makes duplicate SKU lines impossible).
CREATE TABLE order_items (
    order_id text    NOT NULL REFERENCES orders (id),
    sku      text    NOT NULL REFERENCES products (sku),
    quantity integer NOT NULL CHECK (quantity > 0),
    PRIMARY KEY (order_id, sku)
);

-- Work table used as the queue (decision D4). One job per order.
-- state: pending -> claimed -> done, or claimed -> pending (retry) -> ... -> dead.
CREATE TABLE jobs (
    id               bigserial   PRIMARY KEY,
    order_id         text        NOT NULL UNIQUE REFERENCES orders (id),
    state            text        NOT NULL DEFAULT 'pending'
                     CHECK (state IN ('pending', 'claimed', 'done', 'dead')),
    attempts         integer     NOT NULL DEFAULT 0 CHECK (attempts >= 0),
    max_attempts     integer     NOT NULL DEFAULT 5 CHECK (max_attempts > 0),
    next_run_at      timestamptz NOT NULL DEFAULT now(),
    locked_by        text,
    lease_expires_at timestamptz,
    last_error       text,
    created_at       timestamptz NOT NULL DEFAULT now(),
    updated_at       timestamptz NOT NULL DEFAULT now()
);

-- Speeds up the worker's claim query (pending jobs that are due, claimed jobs whose lease ended).
CREATE INDEX jobs_claimable_idx ON jobs (next_run_at) WHERE state IN ('pending', 'claimed');
